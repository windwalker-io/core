<?php

declare(strict_types=1);

namespace Windwalker\Core\Database\Exporter;

use DomainException;
use Psr\Http\Message\StreamInterface;
use Windwalker\Database\Manager\TableManager;

/**
 * The Exporter class.
 *
 * @since  3.0
 */
class PostgresqlExporter extends AbstractCliExporter
{
    protected function exportSqlCli(string $file): ?string
    {
        return $this->dump($file, 'plain') ? 'sql' : null;
    }

    protected function exportNativeCli(string $file): ?string
    {
        return $this->dump($file, 'custom') ? 'dump' : null;
    }

    protected function dump(string $file, string $format): bool
    {
        $binary = $this->findExecutable('pg_dump', 'PG_DUMP_BINARY');
        if ($binary === null) {
            return false;
        }

        $options = $this->options();
        $command = [$binary, '--no-password', '--format=' . $format, '--file=' . $file];
        foreach (['host' => $options->host, 'port' => $options->port, 'username' => $options->user] as $key => $value) {
            if ($value !== null && $value !== '') {
                $command[] = '--' . $key . '=' . $value;
            }
        }
        $command[] = '--dbname=' . $options->dbname;
        $this->process($command, ['PGPASSWORD' => $options->password ?? ''])->mustRun();

        return true;
    }

    protected function phpPreamble(): string
    {
        return 'BEGIN';
    }

    protected function writeSchema(StreamInterface $stream, string $schema): void
    {
        $this->writeSql($stream, 'CREATE SCHEMA IF NOT EXISTS ' . $this->db->quoteName($schema, true));
    }

    protected function tableDdl(TableManager $manager): array
    {
        $schema = $manager->schemaName ?: 'public';
        $table = $manager->getName();
        $rows = $this->db->prepare(
            'SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull, '
            . 'a.attidentity, a.attgenerated, pg_get_expr(d.adbin, d.adrelid) AS expression '
            . 'FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid '
            . 'JOIN pg_namespace n ON n.oid=c.relnamespace '
            . 'LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum '
            . 'WHERE a.attnum>0 AND NOT a.attisdropped AND n.nspname=' . $this->db->quote($schema)
            . ' AND c.relname=' . $this->db->quote($table) . ' ORDER BY a.attnum'
        )->all();
        $columns = [];
        foreach ($rows as $row) {
            $definition = $this->db->quoteName($row['attname'], true) . ' ' . $row['type'];
            if ($row['attidentity'] !== '') {
                $definition .= $row['attidentity'] === 'a'
                    ? ' GENERATED ALWAYS AS IDENTITY'
                    : ' GENERATED BY DEFAULT AS IDENTITY';
                $sequenceName = $this->db->prepare(
                    'SELECT pg_get_serial_sequence(' . $this->db->quote(
                        $this->db->quoteName($schema . '.' . $table)
                    ) . ', ' . $this->db->quote($row['attname']) . ')'
                )->result();
                $sequence = $this->db->prepare(
                    'SELECT * FROM pg_sequence WHERE seqrelid=' . $this->db->quote($sequenceName) . '::regclass'
                )->get();
                if (!$sequence) {
                    throw new DomainException('PostgreSQL identity sequence metadata is unavailable.');
                }
                $definition .= ' (SEQUENCE NAME ' . $sequenceName
                    . ' START WITH ' . $sequence['seqstart'] . ' INCREMENT BY ' . $sequence['seqincrement']
                    . ' MINVALUE ' . $sequence['seqmin'] . ' MAXVALUE ' . $sequence['seqmax']
                    . ' CACHE ' . $sequence['seqcache'] . ($sequence['seqcycle'] ? ' CYCLE' : ' NO CYCLE') . ')';
            } elseif ($row['attgenerated'] !== '') {
                $definition .= ' GENERATED ALWAYS AS (' . $row['expression'] . ') STORED';
            } elseif ($row['expression'] !== null) {
                $definition .= ' DEFAULT ' . $row['expression'];
            }
            if ($row['attnotnull']) {
                $definition .= ' NOT NULL';
            }
            $columns[] = $definition;
        }
        if ($columns === []) {
            throw new DomainException("No PostgreSQL column metadata for {$schema}.{$table}.");
        }

        return ['CREATE TABLE ' . $this->db->quoteName($schema . '.' . $table)
            . " (\n" . implode(",\n", $columns) . "\n)"];
    }

    protected function exportPhp(StreamInterface $stream): void
    {
        $unsupported = $this->db->prepare(
            'SELECT count(*) FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace '
            . "WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND t.typtype='d'"
        )->result();
        if ($unsupported) {
            throw new DomainException('PHP PostgreSQL export does not support domains; use pg_dump.');
        }
        $sequences = $this->db->prepare(
            "SELECT * FROM pg_sequences WHERE schemaname NOT IN ('pg_catalog', 'information_schema')"
        )->all();
        foreach ($sequences as $sequence) {
            $schema = $sequence['schemaname'];
            $name = $this->db->quoteName($schema . '.' . $sequence['sequencename']);
            $identity = $this->db->prepare(
                "SELECT count(*) FROM pg_depend WHERE classid='pg_class'::regclass "
                . 'AND objid=' . $this->db->quote($schema . '.' . $sequence['sequencename'])
                . "::regclass AND deptype='i'"
            )->result();
            if (!$identity) {
                $this->writeSchema($stream, $schema);
                $this->writeSql(
                    $stream,
                    'CREATE SEQUENCE ' . $name . ' INCREMENT BY ' . (int) $sequence['increment_by']
                    . ' MINVALUE ' . $sequence['min_value'] . ' MAXVALUE ' . $sequence['max_value']
                    . ' START WITH ' . $sequence['start_value'] . ' CACHE ' . (int) $sequence['cache_size']
                    . ($sequence['cycle'] ? ' CYCLE' : ' NO CYCLE')
                );
            }
        }
        $enums = $this->db->prepare(
            'SELECT n.nspname, t.typname, e.enumlabel FROM pg_type t '
            . 'JOIN pg_namespace n ON n.oid=t.typnamespace JOIN pg_enum e ON e.enumtypid=t.oid '
            . "WHERE n.nspname NOT IN ('pg_catalog','information_schema') ORDER BY t.oid,e.enumsortorder"
        )->all();
        $types = [];
        foreach ($enums as $enum) {
            $key = $enum['nspname'] . '.' . $enum['typname'];
            $types[$key][] = $this->db->quote($enum['enumlabel']);
            $this->writeSchema($stream, $enum['nspname']);
        }
        foreach ($types as $name => $labels) {
            $this->writeSql($stream, 'CREATE TYPE ' . $this->db->quoteName($name)
                . ' AS ENUM (' . implode(', ', $labels) . ')');
        }
        parent::exportPhp($stream);
        foreach ($sequences as $sequence) {
            $name = $this->db->quoteName($sequence['schemaname'] . '.' . $sequence['sequencename']);
            $state = $this->db->prepare('SELECT last_value, is_called FROM ' . $name)->get();
            if ($state !== null) {
                $this->writeSql(
                    $stream,
                    'SELECT setval(' . $this->db->quote($sequence['schemaname'] . '.' . $sequence['sequencename'])
                    . ', ' . $state['last_value'] . ', ' . ($state['is_called'] ? 'true' : 'false') . ')'
                );
            }
        }
    }

    protected function writableColumns(TableManager $manager): array
    {
        $excluded = $this->db->prepare(
            'SELECT a.attname FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid '
            . 'JOIN pg_namespace n ON n.oid=c.relnamespace WHERE a.attgenerated<>\'\' AND n.nspname='
            . $this->db->quote($manager->schemaName ?: 'public') . ' AND c.relname='
            . $this->db->quote($manager->getName())
        )->loadColumn()->dump();

        return array_filter(
            parent::writableColumns($manager),
            static fn($column) => !in_array($column->getColumnName(), $excluded, true)
        );
    }

    protected function tablePostDdl(TableManager $manager): array
    {
        $name = $this->db->quoteName(($manager->schemaName ?: 'public') . '.' . $manager->getName());
        $relation = $this->db->quote($name) . '::regclass';
        $local = [];
        $references = [];
        foreach ($this->db->prepare(
            'SELECT pg_get_indexdef(i.indexrelid) AS definition FROM pg_index i '
            . 'WHERE i.indrelid=' . $relation . ' AND NOT EXISTS '
            . '(SELECT 1 FROM pg_constraint c WHERE c.conindid=i.indexrelid)'
        ) as $row) {
            $local[] = $row['definition'];
        }
        foreach ($this->db->prepare(
            'SELECT conname, contype, pg_get_constraintdef(oid, true) AS definition FROM pg_constraint '
            . 'WHERE conrelid=' . $relation . " AND contype IN ('p','u','f','c','x')"
        ) as $row) {
            $sql = 'ALTER TABLE ' . $name . ' ADD CONSTRAINT '
                . $this->db->quoteName($row['conname'], true) . ' ' . $row['definition'];
            if ($row['contype'] === 'f') {
                $references[] = $sql;
            } else {
                $local[] = $sql;
            }
        }

        return [$local, $references];
    }

    protected function insertValuesClause(): string
    {
        return ' OVERRIDING SYSTEM VALUE VALUES (';
    }

    protected function phpEpilogue(): string
    {
        return 'COMMIT';
    }

    protected function literal(mixed $value, ?string $type = null): string
    {
        if ($value !== null && $type === 'bytea') {
            $bytes = is_resource($value) ? stream_get_contents($value) : $value;
            if (!is_string($bytes)) {
                throw new \RuntimeException('Unable to read PostgreSQL bytea data.');
            }

            return "decode('" . bin2hex($bytes) . "', 'hex')";
        }
        if (is_bool($value)) {
            return $value ? 'TRUE' : 'FALSE';
        }

        return parent::literal($value, $type);
    }
}
